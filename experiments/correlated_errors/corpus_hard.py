def build_hard() -> list[dict[str, object]]:
    """Return the hard-facts corpus as a list of dicts (id/claim_text/oracle_value/source/domain)."""
    out: list[dict[str, object]] = []
    for fact_id, question, oracle, source, domain in HARD_FACTS:
        out.append({
            "id": fact_id,
            "claim_text": question,
            "oracle_value": oracle,
            "oracle_unit": "",
            "source": source,
            "domain": domain,
        })
    return out


