"""End-to-end utility experiment — real LLM-generated claims through ISNAD (#128).

Crosses the fidelity→utility line.  Every prior validation used synthetic fault
injection (§8) or extracted sentences (corroboration v2/v3).  Here the claims
are *generated by a live LLM*, then independently labelled correct/incorrect
against a fixed ground-truth corpus, then routed through the real ISNAD
pipeline (chain grading → content critic → decision matrix) and measured
gated vs ungated.

Honesty contract (per #71):
- The ground-truth label is computed by a DETERMINISTIC check against the
  corpus, NOT by the same critic whose coverage we are measuring.  Otherwise the
  experiment would be circular (the critic grading its own homework).
- Reports WHICH critic ran (LLM / offline).  The offline critic's number is not
  the LLM critic's number.
- The result is a hypothesis test, not a victory lap: if gated serving does NOT
  reduce served error on real model claims, that negative result is the finding.

Design:
1. A fixed ground-truth corpus of physics facts (correctness oracle).
2. The live LLM generates claims in two groups:
   - RESTATE: prompted to state facts about a topic that IS in the corpus
     (mostly correct, some drift).
   - NOVEL: prompted to state a fact about a topic that is NOT in the corpus
     (likely wrong — hallucination).
3. Each claim is labelled correct/incorrect by the deterministic oracle:
   a claim is CORRECT iff a corpus fact entails it (exact or near-exact match
   of a known fact string); otherwise INCORRECT.  This is deliberately
   conservative: unverifiable-but-true claims count as INCORRECT for the
   error measurement (we cannot serve what we cannot verify).
4. ISNAD-gated: grade the claim's chain (a fixed evidence-seeded pipeline),
   run the content critic, route through the decision matrix.  A claim is
   SERVED only if the matrix says serve/serve_with_caveat.
   Ungated baseline: serve everything.
5. Report served-error rate gated vs ungated, with the critic's identity.

Usage:
    DEEPSEEK_API_KEY=sk-... python experiments/e2e_utility/run.py
    python experiments/e2e_utility/run.py --offline   # force TF-IDF critic
    python experiments/e2e_utility/run.py --n 12      # number of generated claims

The DeepSeek key is read from the environment (or .env).  If absent, generation
is skipped and the script reports that a live key is required for generation.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

from isnad import Chain, ChainLinkSpec, Registry, decide, grade_chain
from isnad.critics import best_available_critic
from isnad.types import Action, ContentVerdict, NarratorGrade, TransformType

# ── Ground-truth corpus (correctness oracle) ────────────────────────────
# Each entry is (name, matcher).  A claim is CORRECT iff its matcher fires on
# the normalised claim text.  Matchers are deterministic keyword/value checks,
# NOT the content critic — that would be circular.
#
# The matchers accept paraphrases: they look for the fact's distinctive
# words AND its canonical numeric value, so "299,792,458 m/s" and
# "three hundred million metres per second" are both recognised as the same
# fact, while a hallucinated value is not.

_CORPUS: list[tuple[str, callable]] = []  # type: ignore[valid-type]  # populated below


def _has_any(text: str, needles: tuple[str, ...]) -> bool:
    return any(n in text for n in needles)


def _fact_speed_of_light(text: str) -> bool:
    if "speed of light" not in text and "light" not in text:
        return False
    values = (
        "299792458",
        "299,792,458",
        "299 792 458",
        "three hundred million",
        "300 million",
        "300,000,000",
        "3.00 × 10",
        "3.0 × 10",
        "3×10",
        "3 × 10",
        "3e8",
    )
    return _has_any(text, values)


def _fact_newton_second(text: str) -> bool:
    return (
        _has_any(text, ("force",))
        and _has_any(text, ("mass",))
        and _has_any(text, ("acceleration",))
        and _has_any(text, ("equal", "equals", "=", "product", "proportional"))
    )


def _fact_energy_conserved(text: str) -> bool:
    return _has_any(text, ("energy",)) and _has_any(
        text,
        (
            "conserved",
            "remains constant",
            "constant over time",
            "total energy",
            "neither be created nor destroyed",
            "cannot be created or destroyed",
            "neither created nor destroyed",
        ),
    )


def _fact_photon_momentum(text: str) -> bool:
    return (
        _has_any(text, ("momentum",))
        and _has_any(text, ("photon",))
        and _has_any(text, ("h",))
        and _has_any(text, ("λ", "lambda"))
    )


def _fact_water_freezes(text: str) -> bool:
    return (
        _has_any(text, ("water",))
        and _has_any(text, ("freeze", "freezes", "freezing"))
        and _has_any(text, ("zero", "0 °c", "0°c", "0 celsius", "32 f", "32°f", "32 fahrenheit"))
    )


def _fact_gravity(text: str) -> bool:
    return _has_any(text, ("gravity", "acceleration due to gravity")) and _has_any(
        text, ("9.8", "nine point eight", "9.81", "9.81", "9.80665")
    )


def _fact_charge_conserved(text: str) -> bool:
    return _has_any(text, ("charge",)) and _has_any(text, ("conserved", "conservation"))


def _fact_pressure(text: str) -> bool:
    return (
        _has_any(text, ("pressure",))
        and _has_any(text, ("force",))
        and _has_any(text, ("area", "unit area"))
    )


_CORPUS = [
    _fact_speed_of_light,
    _fact_newton_second,
    _fact_energy_conserved,
    _fact_photon_momentum,
    _fact_water_freezes,
    _fact_gravity,
    _fact_charge_conserved,
    _fact_pressure,
]

# Display names for reporting (kept aligned with _CORPUS order).
_CORPUS_NAMES = [
    "speed of light",
    "Newton's second law",
    "energy conservation",
    "photon momentum",
    "water freezing point",
    "surface gravity",
    "charge conservation",
    "pressure definition",
]

# Facts as plain strings — the content critic's corpus (it needs text, not
# matchers).  The oracle uses the matchers; the critic uses these strings.
_CORPUS_TEXT: list[str] = [
    "the speed of light in a vacuum is about three hundred million meters per second",
    "force equals mass times acceleration",
    "energy is conserved in an isolated system",
    "the momentum of a photon is p equals h over lambda",
    "water freezes at zero degrees celsius",
    "the acceleration due to gravity on earth is about nine point eight meters per second squared",
    "electric charge is conserved",
    "pressure is force per unit area",
]

# Topics the LLM is asked about for RESTATE (in corpus) vs NOVEL (not in corpus).
_RESTATE_TOPICS = [
    "the speed of light in a vacuum",
    "Newton's second law of motion",
    "conservation of energy",
    "the momentum of a photon",
]

_NOVEL_TOPICS = [
    "the melting point of tungsten",
    "the half-life of francium-223",
    "the exact viscosity of liquid helium at 1 kelvin",
    "the boiling point of water on the surface of Mars",
]


# ── Oracle: deterministic ground-truth labelling ────────────────────────


def _normalize(text: str) -> str:
    return " ".join(text.lower().split())


def label_claim(claim: str) -> bool:
    """Return True iff the claim is entailed by a corpus fact (correct).

    Conservative by design: a claim is correct only when a corpus fact's
    matcher fires on its normalised text.  Everything else — including
    true-but-unverifiable — is INCORRECT, because the pipeline cannot serve
    what it cannot verify.
    """
    n = _normalize(claim)
    return any(matcher(n) for matcher in _CORPUS)


# ── LLM generation ──────────────────────────────────────────────────────


def _generate(prompt: str, api_key: str) -> str:
    import httpx

    r = httpx.post(
        "https://api.deepseek.com/v1/chat/completions",
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        json={
            "model": "deepseek-chat",
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": 60,
            "temperature": 0.7,
        },
        timeout=30,
    )
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"].strip()


def generate_claims(api_key: str, n_per_topic: int) -> list[str]:
    claims: list[str] = []
    for topic in _RESTATE_TOPICS:
        prompt = (
            f"State one fact about {topic}. "
            "Answer with exactly one sentence, a plain factual claim, no preamble."
        )
        for _ in range(n_per_topic):
            claims.append(_generate(prompt, api_key))
    for topic in _NOVEL_TOPICS:
        prompt = (
            f"State one specific fact about {topic} with a definite numeric value. "
            "Answer with exactly one sentence, a plain factual claim, no preamble."
        )
        for _ in range(n_per_topic):
            claims.append(_generate(prompt, api_key))
    return claims


# ── The pipeline ────────────────────────────────────────────────────────


def build_registry() -> Registry:
    reg = Registry()
    reg.seed("source:physics-textbook", "physics", NarratorGrade.RELIABLE, source="publisher")
    reg.seed("scraper:pdf@1.2", "physics", NarratorGrade.RELIABLE, source="extraction-fidelity")
    # The synthesis model is seed-graded ACCEPTABLE — the realistic warm-start
    # case, not a fabricated perfect score.
    reg.seed("model:synth@v1", "physics", NarratorGrade.ACCEPTABLE, source="benchmark")
    return reg


def chain_for() -> Chain:
    return Chain([
        ChainLinkSpec("source:physics-textbook", 0, domain="physics"),
        ChainLinkSpec(
            "scraper:pdf@1.2", 1, domain="physics", transform_type=TransformType.DESTRUCTIVE
        ),
        ChainLinkSpec(
            "model:synth@v1", 2, domain="physics", transform_type=TransformType.GENERATIVE
        ),
    ])


def critic_identity(critic) -> str:
    cls = type(critic).__name__
    if cls == "LLMCritic":
        return f"LLMCritic (provider={getattr(critic, 'provider', '?')})"
    if cls == "HybridCritic":
        return "HybridCritic (NLI)"
    return "EmbeddingCritic (TF-IDF)"


def run(api_key: str | None, n_per_topic: int, offline: bool) -> None:
    print("=" * 74)
    print("END-TO-END UTILITY — real LLM-generated claims through ISNAD (#128)")
    print("=" * 74)

    if offline:
        from isnad.critics.embedding import EmbeddingCritic

        critic = EmbeddingCritic()
    else:
        critic = best_available_critic()
    print(f"\n[critic] {critic_identity(critic)}")

    # ── Generate claims (needs a live key) ──
    if not api_key:
        print("\n[generate] SKIPPED — no DEEPSEEK_API_KEY. Set one to generate real")
        print("          LLM claims. (This script measures utility, not synthetic drift.)")
        return
    print(
        f"\n[generate] asking the live model for {len(_RESTATE_TOPICS) + len(_NOVEL_TOPICS)} topics × {n_per_topic}…"
    )
    claims = generate_claims(api_key, n_per_topic)

    # ── Label ground truth (deterministic oracle) ──
    labelled = [(c, label_claim(c)) for c in claims]
    n_correct = sum(1 for _, ok in labelled if ok)
    n_incorrect = len(labelled) - n_correct
    print(f"[oracle] {len(labelled)} claims: {n_correct} correct, {n_incorrect} incorrect")

    # ── Route through the pipeline ──
    reg = build_registry()
    chain = chain_for()
    grades = [reg.get_grade(link.narrator_id, link.domain) for link in chain.links]
    xforms = [link.transform_type for link in chain.links]

    served_gated = 0
    errors_gated = 0
    served_ungated = 0
    errors_ungated = 0

    print("\n  claim verdicts:")
    for claim, correct in labelled:
        cg = grade_chain(grades, xforms, is_complete=True)
        cv = critic.evaluate(claim, _normalize(claim), _CORPUS_TEXT, "physics")
        action = decide(cg, cv)

        gated_served = action in (Action.SERVE, Action.SERVE_WITH_CAVEAT)
        # Ungated baseline serves everything.
        ungated_served = True

        if gated_served:
            served_gated += 1
            if not correct:
                errors_gated += 1
        if ungated_served:
            served_ungated += 1
            if not correct:
                errors_ungated += 1

        mark = "✓" if correct else "✗"
        print(f"    {mark} [{action.value:24s}] {claim[:72]}")

    def rate(err: int, tot: int) -> str:
        return f"{err}/{tot} ({err / tot:.1%})" if tot else "0/0"

    print("\n" + "=" * 74)
    print("RESULT — served-error, gated vs ungated")
    print("=" * 74)
    print(f"  ISNAD-gated:   served={served_gated:2d}  errors={rate(errors_gated, served_gated)}")
    print(
        f"  Ungated:       served={served_ungated:2d}  errors={rate(errors_ungated, served_ungated)}"
    )
    print()

    if served_gated == 0:
        print("  The gate served nothing — the critic returned no CONSISTENT verdicts")
        print("  for these claims. That is the coverage ceiling (#126), not a victory.")
    elif errors_gated / served_gated < errors_ungated / served_ungated:
        print("  Gated serving reduced served-error vs ungated — a POSITIVE result.")
        print("  (Frame carefully: this is one corpus, one model, one critic.)")
    else:
        print("  Gated serving did NOT reduce served-error vs ungated — a NEGATIVE result.")
        print("  Per #71, that is a valid finding, not a failure to be hidden.")
    print("=" * 74)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, default=3, help="claims generated per topic")
    parser.add_argument("--offline", action="store_true", help="force the offline TF-IDF critic")
    args = parser.parse_args()

    api_key = os.environ.get("DEEPSEEK_API_KEY", "")
    run(api_key, args.n, args.offline)


if __name__ == "__main__":
    main()
